CREATE SEQUENCE SEQ_CONFERENCIA_FONTE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CONFERENCIA_ITEM START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CONFERENCIA_EVIDENCIA START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_AUDITORIA_CONFERENCIA START WITH 1 INCREMENT BY 1 NOCACHE;

